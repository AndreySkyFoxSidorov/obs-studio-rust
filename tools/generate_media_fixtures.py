"""Explicit offline FFmpeg test-oracle generator. Never imported by production.

All signals are synthetic lavfi testsrc2/sine, <=0.6s,64x48,one encoder thread.
The executable is supplied by the operator. No devices, network or user media.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess


def run(argv):
    child = subprocess.run(argv, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                           stderr=subprocess.PIPE, timeout=30, check=False)
    if child.returncode:
        raise RuntimeError(child.stderr.decode("utf-8", errors="replace")[:8192])
    return child.stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ffmpeg", type=Path, required=True)
    parser.add_argument("--ffprobe", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--no-pns", action="store_true", help="separate deterministic AAC spectral oracle without noise substitution")
    args = parser.parse_args()
    ffmpeg = args.ffmpeg.resolve(strict=True)
    ffprobe = args.ffprobe.resolve(strict=True)
    args.out.mkdir(parents=True, exist_ok=True)
    cases = [("cavlc", "baseline", "cabac=0:bframes=0:ref=1"),
             ("cabac_b", "high", "cabac=1:bframes=2:ref=2")]
    report = {"schema": 1, "signals": "original synthetic testsrc2 and1kHz sine; no devices/user content",
              "ffmpeg_sha256": hashlib.sha256(ffmpeg.read_bytes()).hexdigest(),
              "ffmpeg_version": run([str(ffmpeg), "-version"]).decode("utf-8").splitlines()[0],
              "production_dependency": False, "aac_rmse_tolerance": 0.00002,
              "aac_pns_enabled": not args.no_pns,
              "aac_peak_tolerance": 0.0002, "h264_comparison": "exact cropped planar Y,U,V bytes",
              "cases": []}
    for name, profile, options in cases:
        movie = args.out / (name + ".mp4")
        yuv = args.out / (name + ".yuv")
        pcm = args.out / (name + ".f32le")
        generated = [str(ffmpeg), "-hide_banner", "-loglevel", "error", "-y", "-nostdin",
                     "-f", "lavfi", "-i", "testsrc2=size=64x48:rate=10:duration=0.6",
                     "-f", "lavfi", "-i", "sine=frequency=1000:sample_rate=48000:duration=0.6",
                     "-map", "0:v:0", "-map", "1:a:0", "-c:v", "libx264", "-threads:v", "1",
                     "-profile:v", profile, "-pix_fmt", "yuv420p", "-qp", "20", "-x264-params",
                     options + ":threads=1:keyint=10:min-keyint=10:scenecut=0",
                     "-colorspace", "bt709", "-color_primaries", "bt709", "-color_trc", "bt709",
                     "-c:a", "aac", "-profile:a", "aac_low", "-threads:a", "1", "-b:a", "96000",
                     "-ac", "1", "-ar", "48000", "-movflags", "+faststart", "-t", "0.6", str(movie)]
        if args.no_pns:
            generated[-1:-1] = ["-aac_pns", "0"]
        run(generated)
        run([str(ffmpeg), "-hide_banner", "-loglevel", "error", "-y", "-nostdin", "-threads", "1",
             "-i", str(movie), "-map", "0:v:0", "-vsync", "0", "-pix_fmt", "yuv420p", "-f", "rawvideo", str(yuv)])
        run([str(ffmpeg), "-hide_banner", "-loglevel", "error", "-y", "-nostdin", "-threads", "1",
             "-i", str(movie), "-map", "0:a:0", "-c:a", "pcm_f32le", "-f", "f32le", str(pcm)])
        metadata = json.loads(run([str(ffprobe), "-v", "error", "-show_streams", "-show_packets",
                                  "-of", "json", str(movie)]))
        if len(movie.read_bytes()) > 128_000 or len(yuv.read_bytes()) != 64 * 48 * 3 // 2 * 6 or pcm.stat().st_size > 200_000:
            raise RuntimeError("synthetic fixture exceeded the declared shape")
        meta = args.out / (name + ".probe.json")
        meta.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
        record = {"name": name, "command": generated, "files": {}}
        for path in (movie, yuv, pcm, meta):
            data = path.read_bytes()
            record["files"][path.name] = {"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
            Path(str(path) + ".attribution").write_text(
                "asset: " + path.name + "\nauthor: SkyLive contributors\nsource: original synthetic signals generated by tools/generate_media_fixtures.py\nlicense: CC0-1.0\nnotes: external FFmpeg/libx264 test oracle only; no production linkage or executable bundling\n",
                encoding="utf-8")
        report["cases"].append(record)
    (args.out / "manifest.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"cases": len(cases), "out": str(args.out.resolve())}))


if __name__ == "__main__":
    main()
