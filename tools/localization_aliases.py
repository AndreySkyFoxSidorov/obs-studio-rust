#!/usr/bin/env python3
"""Generate stable original-English aliases, never reading the editable CSV."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

from localization_catalog import build_catalog

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "crates/host/src/localization_aliases.rs"


def qt_text(text: str) -> str:
    begin = text.rfind("(&")
    if begin >= 0 and text.endswith(")"):
        letter = text[begin + 2:-1]
        if len(letter) == 1 and letter.isalnum():
            return qt_text(text[:begin].rstrip())
    result = []
    index = 0
    while index < len(text):
        char = text[index]
        index += 1
        if char != "&":
            result.append(char)
            continue
        if text[index:index + 1] == "&":
            result.append("&")
            index += 1
            continue
        tail = text[index:]
        end = tail.find(";")
        entity = 0 <= end <= 12 and all(ch.isascii() and ch.isalnum() or ch == "#" for ch in tail[:end])
        if entity or not tail or not tail[0].isalnum():
            result.append("&")
    return "".join(result)


def normalize(text: str) -> str:
    value = qt_text(text)
    if value.endswith("…"):
        return value[:-1]
    if value.endswith("...") and not value[:-3].endswith("."):
        return value[:-3]
    return value


def priority(key: str) -> int:
    return 2 if key.startswith("Module.") else 1 if key.startswith("SkyLive.") else 0


def aliases(rows: dict) -> list[tuple[str, str, str]]:
    candidates = sorted((normalize(values.get("en-US", "")), priority(key), key, values.get("en-US", ""))
                        for key, values in rows.items()
                        if not key.startswith("SkyLive.CameraControl.") and normalize(values.get("en-US", "")))
    result = {}
    for normalized, _, key, english in candidates:
        result.setdefault(normalized, (normalized, key, english))
    return list(result.values())


def rust_string(text: str) -> str:
    escaped = []
    for char in text:
        escaped.append({"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}.get(char,
                       f"\\u{{{ord(char):x}}}" if ord(char) < 32 else char))
    return '"' + "".join(escaped) + '"'


def generate() -> str:
    _, rows, _, _ = build_catalog()
    lines = ["// Generated by tools/localization_aliases.py from original source catalog; do not edit.",
             "// Editable translations.csv is deliberately not an input.",
             "#[rustfmt::skip]", "const ORIGINAL_ALIASES: &[(&str, &str, &str)] = &["]
    lines.extend("    (" + ", ".join(map(rust_string, row)) + ")," for row in aliases(rows))
    return "\n".join(lines + ["];", ""])


def self_test() -> None:
    fixtures = {"&Save...": "Save", "Save…": "Save", "Wait....": "Wait....",
                "A & B": "A & B", "A&B": "AB", "R&&D": "R&D", "Text &amp; HTML": "Text &amp; HTML",
                "Настройки (&S)": "Настройки", "Label (&Ж)": "Label", "Label (&SS)": "Label (SS)",
                "Keep whitespace ": "Keep whitespace "}
    for source, expected in fixtures.items():
        assert normalize(source) == expected, (source, normalize(source), expected)
    rows = {"Module.B": {"en-US": "&Save..."}, "SkyLive.A": {"en-US": "Save…"},
            "Z": {"en-US": "Save"}, "A": {"en-US": "&Save..."}, "Empty": {"en-US": ""}}
    assert aliases(rows) == [("Save", "A", "&Save...")]


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        self_test()
        print(json.dumps({"self_test": "passed"}))
        return
    source = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != source:
            raise SystemExit("Original-English aliases need regeneration: python tools/localization_aliases.py")
    else:
        OUTPUT.write_text(source, encoding="utf-8", newline="\n")
    print(json.dumps({"check": args.check, "aliases": source.count("    ("), "path": str(OUTPUT)}))


if __name__ == "__main__":
    main()
